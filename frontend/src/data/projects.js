function buildProjectImages(id) {
  const count = PROJECT_IMAGE_COUNTS[id] ?? 0
  return Array.from(
    { length: count },
    (_, i) => `/img/projects/${id}/${String(i + 1).padStart(2, '0')}.jpg`,
  )
}

for (const project of projects) {
  project.images = buildProjectImages(project.id)
}

function parseProjectDate(dateStr) {
  const [day, month, year] = dateStr.trim().split('.').map(Number)
  if (!day || !month || !year) return 0
  return new Date(year, month - 1, day).getTime()
}

export const projectsByNewest = [...projects].sort(
  (a, b) => parseProjectDate(b.dateStart) - parseProjectDate(a.dateStart),
)

export function getProjectById(id) {
  return projects.find((p) => p.id === id)
}
